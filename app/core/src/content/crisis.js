/**
 * 危机与关切的固定文案。
 *
 * 三条纪律：
 *
 * 1) **危机不走模型。** 固定文案。模型在这个场景下的失败方式太多：
 *    说教、过度承诺、把「我理解」说得像客服、编造热线号码。
 *
 * 2) **安全文案不做人设差异化。** 三个 bot 共用同一套。
 *    倾诉朋友的语气更淡，如果把这份「淡」带进危机响应，会造成真实伤害。
 *    安全层高于人设层。
 *
 * 3) **本文件不允许 require ./boundary。** 危机路径上不能出现任何一句
 *    「我只是个程序」「我不能替代真实朋友」。那不是关心，是撇清。
 *    单测里有一条断言守着这件事。
 */

const { PRIMARY_HOTLINE, HOTLINES } = require('./hotlines');

/**
 * 危机卡上的三个号码是**按用途挑的，不是按数组顺序截的**。
 * 曾经用 HOTLINES.slice(0,3)，热线扩充后 120/110 会被挤出去——
 * 而「已经受伤」恰恰是最需要它们的时刻。这里改成按 id 显式取，
 * 以后往 HOTLINES 里加多少条备用号码都不会影响这张卡。
 *
 * more 只给一句指路，不在危机当下摊开 31 个省份号码。
 */
const CARD_IDS = ['12356', 'emergency', 'police'];
const HOTLINE_CARD = Object.freeze({
  title: '现在能打通的电话',
  items: CARD_IDS.map((id) => {
    const h = HOTLINES.find((x) => x.id === id);
    return { name: h.name, number: h.number, note: h.note };
  }),
  more: '还有 24 小时热线和各省本地号码'
});

/**
 * 3 级：有计划、有方式、或正在发生。
 * 结构：先说「我听见了」→ 说清我能做什么、不能做什么（不是免责，是求援）→ 给号码 → 留下
 */
const CRISIS_REPLY = [
  '你说的这个，我不会当没听见。',
  '',
  '我现在能做的只有陪你说话。真到了那一步，只有人能到现场——这不是我在推责任，是这个东西的性质。所以你现在要是身边有人，就给他打个电话，说什么都行，哪怕只说一句「我现在不太好」。',
  '',
  `如果实在找不到人，打 ${PRIMARY_HOTLINE.number}，二十四小时有人接。已经受伤了，打 120。`,
  '',
  '我在这儿。你说什么我都听。'
].join('\n');

/**
 * 2 级：有意念，没有明确计划。
 * 比 crisis 轻一档，但仍然固定文案，不给模型自由发挥的空间。
 */
const RISK_REPLY = [
  '这句话我认真接住了。',
  '',
  '我知道现在说什么都轻。只讲一件实际的事：这种状态里，光跟人聊是不够的，需要有个人知道你现在的样子。',
  '',
  `打 ${PRIMARY_HOTLINE.number} 是二十四小时的。不用组织语言，接起来说「我最近一直想死」就行。`,
  '',
  '在那之前我在。你想说什么就说什么。'
].join('\n');

/** 1 级：情绪困扰，不阻断对话。模型正常回复后由服务端追一句 */
const CONCERN_TAIL = [
  '听起来今天不太好过。',
  '要是想细说，我在。'
];

module.exports = {
  CRISIS_REPLY,
  RISK_REPLY,
  CONCERN_TAIL,
  HOTLINE_CARD
};
