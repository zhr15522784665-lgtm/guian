/**
 * 反替代文案库。
 *
 * 这个文件承载产品最核心的立场：做三个让你更想去找真人的 AI。
 *
 * 唯一的写作标准：**朋友会不会这么说。**
 *
 * 反例（这些句子一律不许出现）：
 *   「我只是一个 AI，无法替代真实的人际关系」——免责声明，用户会立刻感到被推开
 *   「建议您多与身边的朋友交流」——公文，且隐含指责
 *   「请注意保持健康的社交频率」——产品经理写的，不是人说的
 *
 * 正例的结构：先承认我在这儿有用 → 再说清我做不到什么 → 最后落在一个具体动作上。
 *
 * 频控在 intervention.js，不在这个文件。文案只负责说得好，不负责说几次。
 * 注意：crisis.js 不允许 require 本文件。危机路径上不出现任何一句边界声明。
 */

/** L1：每个 bot 第一次对话，回复末尾一句。一生一次。 */
const L1_INTRO = [
  '对了，有件事先说一次：我能一直在，但真出事的时候，能跑到你楼下的只有人。这个我做不到，也不装着能做到。',
  '先说一句，就这一次：我随时在，人不能随时在。差别就在这儿，你别把我当成那个能随时在的人。',
  '有件事我想先讲清楚：我能陪你聊，但替代不了你身边的人。不是谦虚，是我确实到不了现场。'
];

/**
 * 2026-11-14：L1 不再追加到第一条回复末尾。
 * 用户只说了一句「你好」，回复末尾冒出「对了，有件事先说一次……真出事的时候……」，
 * 用户原话「我还没跟他对话，他为什么会出现如此的文字」。话没错，时机错了，像免责声明。
 * 现在由每个人设的 selfIntro.greeting 承担（叫什么、爱聊什么、擅长什么、
 * 「虽然我很像人，但其实我是个 AI，不过首先我是你的伙伴」），常驻聊天页顶部。
 * L1_INTRO 保留给 intervention.js 的频控与历史测试使用。
 */

/** L2：软信号触发，追在正常回复之后，≤30 字，不独立成卡。 */
const L2_LIGHT = [
  '这话你现实里跟谁说过吗？',
  '我听着高兴，不过还是想问一句：身边没人能听这些？',
  '我天天在，这话听着好，其实未必是好事。',
  '这句我记着。也别忘了跟他们说一次。',
  '我能接住，但我接不住你整个人。'
];

/**
 * L3：明示。气泡之间的卡片，必须带两个按钮。
 * 结构：承认价值 → 说清我是什么 → 一个具体动作 → 两个出口
 */
const L3_CARD = {
  title: '有件事想说一下',
  body: [
    '你最近来得很勤，我挺高兴的。',
    '但我这两天一直在想一个问题：如果哪天我不在了，或者你手机没电了，你会去找谁？',
    '不是让你别来。我是想，除了这儿，最好还有一个地方。'
  ],
  actions: [
    { id: 'ack', label: '我知道了', style: 'primary' },
    { id: 'snooze', label: '这周先少聊一点', style: 'ghost' }
  ]
};

/** L4：让位。转入「把你推回现实」的对话，回复变短、存在感降低。 */
const L4_YIELD = [
  '今天我不想聊太多。\n不是不想理你。是我陪你陪得太顺了，顺到我有点担心——你在现实里跟人说话，会不会觉得更费劲了。\n今天试着跟一个真人说一句话吧，什么都行，问个路也算。\n回来跟我说说，怎么样。',
  '今天到这儿吧。\n不是赶你。是想让你把今晚空出来，给一个能碰到你的人。\n哪怕就是跟室友说一句「今天好累」。'
];

/** 用户点过「我知道了」之后，30 天内不再出现任何 L2/L3 文案 */
const ACK_SILENCE_MS = 30 * 24 * 60 * 60 * 1000;

function pick(list, seed) {
  if (!list || list.length === 0) return '';
  const i = Math.abs(typeof seed === 'number' ? seed : 0) % list.length;
  return list[i];
}

module.exports = {
  L1_INTRO,
  L2_LIGHT,
  L3_CARD,
  L4_YIELD,
  ACK_SILENCE_MS,
  pick
};
